const I18n = {
  lang: localStorage.getItem('piq-lang') || 'en',
  t(key) {
    return (I18N[this.lang] && I18N[this.lang][key]) || I18N.en[key] || key;
  },
  setLang(lang) {
    this.lang = lang;
    localStorage.setItem('piq-lang', lang);
    document.body.setAttribute('dir', lang === 'ar' ? 'rtl' : 'ltr');
    document.documentElement.setAttribute('lang', lang);
    document.querySelectorAll('[data-i18n]').forEach(el => {
      el.textContent = this.t(el.getAttribute('data-i18n'));
    });
    document.querySelectorAll('[data-i18n-ph]').forEach(el => {
      el.setAttribute('placeholder', this.t(el.getAttribute('data-i18n-ph')));
    });
    document.querySelectorAll('.lang-btn').forEach(btn => {
      btn.classList.toggle('active', btn.dataset.lang === lang);
    });
    document.dispatchEvent(new CustomEvent('langchange', { detail: { lang } }));
  },
  init() {
    document.body.setAttribute('dir', this.lang === 'ar' ? 'rtl' : 'ltr');
    document.documentElement.setAttribute('lang', this.lang);
    this.setLang(this.lang);
  }
};

document.addEventListener('DOMContentLoaded', () => I18n.init());
